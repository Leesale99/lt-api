func TestBriefMarksUnresolvedPointers(t *testing.T) {
	repo := newTestRepo(t)
	catalog := briefCatalog()
	// A stale Go pointer and a scenario no feature file carries.
	catalog[1].Verification.Unit = []string{"internal/kernel/thing/gone_test.go::TestGone"}
	catalog[1].Verification.Gherkin = []string{"docs/spec/features/happy/ride.feature::A scenario that moved"}
	catalog[1].Enforcement[0].Site = "internal/kernel/thing/gone.go::Do"
	repo.writeCatalog(t, catalog)

	code, out, errOut := runBriefTest(t, repo, "R-KERNEL-001")
	if code != 0 {
		t.Fatalf("runBrief = %d, stderr=%s", code, errOut)
	}
	for _, want := range []string{
		"| `unit` | `internal/kernel/thing/gone_test.go::TestGone` | **missing** |",
		"| `gherkin` | `docs/spec/features/happy/ride.feature::A scenario that moved` | **missing** |",
		"**Linked scenarios.** _(none tagged `@rule:R-KERNEL-001` yet)_",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("brief is missing %q", want)
		}
	}
	// Resolution is a display fact, never a failure of the brief itself.
	if strings.Contains(out, "`missing`") {
		t.Error("brief rendered the resolution column as code")
	}
}

func TestBriefUnknownRuleID(t *testing.T) {
	repo := newTestRepo(t)
	repo.writeCatalog(t, briefCatalog())

	code, out, errOut := runBriefTest(t, repo, "R-NOPE-999")
	if code == 0 {
		t.Fatal("runBrief of an unknown rule id exited 0")
	}
	if out != "" {
		t.Errorf("unknown rule id wrote %q to stdout", out)
	}
	if !strings.Contains(errOut, `unknown rule id "R-NOPE-999"`) {
		t.Errorf("stderr = %q, want an unknown-rule-id message", errOut)
	}
}

func TestBriefUnknownModule(t *testing.T) {
	repo := newTestRepo(t)
	repo.writeCatalog(t, briefCatalog())

	code, _, errOut := runBriefTest(t, repo, "--module", "nope")
	if code == 0 {
		t.Fatal("runBrief of an unknown module exited 0")
	}
	if !strings.Contains(errOut, `unknown module "nope"`) {
		t.Errorf("stderr = %q, want an unknown-module message", errOut)
	}
	for _, module := range []string{"game", "identity", "kernel", "ledger", "platform", "schedule"} {
		if !strings.Contains(errOut, module) {
			t.Errorf("unknown-module message does not name %q", module)
		}
	}
}

func TestBriefUsageErrors(t *testing.T) {
	repo := newTestRepo(t)
	repo.writeCatalog(t, briefCatalog())

	for _, args := range [][]string{
		nil,
		{"R-KERNEL-001", "R-KERNEL-002"},
		{"--module", "game", "R-KERNEL-001"},
	} {
		code, out, errOut := runBriefTest(t, repo, args...)
		if code != 2 {
			t.Errorf("runBrief(%v) = %d, want 2", args, code)
		}
		if out != "" {
			t.Errorf("runBrief(%v) wrote %q to stdout", args, out)
		}
		if !strings.Contains(errOut, "spec brief:") {
			t.Errorf("runBrief(%v) stderr = %q, want a spec brief error", args, errOut)
		}
	}
}
