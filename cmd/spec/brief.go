package main

// brief.go emits a Markdown work order for one rule or one module: everything a
// reader needs to pick the rule up — statement, enforcement sites and
// verification pointers (each resolved against the tree today), refusal map,
// fixture, the scenarios tagged with the rule, and the gate to run. It assembles
// the same catalog and the same feature parse `check` uses, and it is a reading aid,
// never a source of truth: the catalog entry and its scenario are the law.

import (
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// briefHeader marks the output as generated in the same voice as the catalog
// views: a brief is derived, so editing it would be editing the wrong file.
const briefHeader = `<!-- GENERATED by spec brief — a reading aid, not a source of truth. -->

`

// briefContext resolves the pointers a work order prints: catalog paths against
// the checkout, scenarios against the parsed feature tree.
type briefContext struct {
	checker *checker
	index   *featureIndex
}

func newBriefContext(root string) *briefContext {
	c := &checker{root: root, fixtures: map[string]bool{}}
	return &briefContext{checker: c, index: c.indexFeatures()}
}

// catalogModules returns the six module names, sorted, straight from the frozen
// enum so a module can never exist in the views and not in the checker.
func catalogModules() []string {
	modules := make([]string, 0, len(moduleEnum))
	for name := range moduleEnum {
		modules = append(modules, name)
	}
	sort.Strings(modules)
	return modules
}

// sortedRules copies the catalog in id order. Every work order is deterministic:
// none of the output depends on YAML or map ordering.
func sortedRules(catalog Catalog) []Rule {
	rules := make([]Rule, len(catalog))
	copy(rules, catalog)
	sort.SliceStable(rules, func(i, j int) bool { return rules[i].ID < rules[j].ID })
	return rules
}

func runBrief(args []string, stdout, stderr io.Writer) int {
	fs := flag.NewFlagSet("spec brief", flag.ContinueOnError)
	fs.SetOutput(stderr)
	rulesPath := fs.String("rules", "docs/spec/rules.yaml", "path to the canonical YAML catalog")
	module := fs.String("module", "", "emit the work order for every rule of one module")
	if err := fs.Parse(args); err != nil {
		return 2
	}

	switch {
	case *module != "" && fs.NArg() > 0:
		fmt.Fprintf(stderr, "spec brief: --module takes no rule id (got %q)\n", fs.Arg(0))
		return 2
	case *module == "" && fs.NArg() != 1:
		fmt.Fprintf(stderr, "spec brief: expected one rule id or --module <module>\n\n"+
			"usage: spec brief R-XXX-NNN\n       spec brief --module %s\n", catalogModules()[0])
		return 2
	case *module != "" && !moduleEnum[*module]:
		fmt.Fprintf(stderr, "spec brief: unknown module %q; one of %s\n",
			*module, strings.Join(catalogModules(), ", "))
		return 1
	}

	catalog, err := loadCatalog(*rulesPath)
	if err != nil {
		fmt.Fprintf(stderr, "spec brief: %v\n", err)
		return 1
	}
	root, err := repoRoot(*rulesPath)
	if err != nil {
		fmt.Fprintf(stderr, "spec brief: %v\n", err)
		return 1
	}
	ctx := newBriefContext(root)
	rules := sortedRules(catalog)

	if *module != "" {
		selected := make([]Rule, 0, len(rules))
		for _, rule := range rules {
			if rule.Module == *module {
				selected = append(selected, rule)
			}
		}
		_, _ = stdout.Write(renderModuleBrief(ctx, selected, *module, *rulesPath))
		return 0
	}

	id := strings.TrimSpace(fs.Arg(0))
	for _, rule := range rules {
		if rule.ID == id {
			_, _ = stdout.Write(renderRuleBrief(ctx, rule, *rulesPath))
			return 0
		}
	}
	fmt.Fprintf(stderr, "spec brief: unknown rule id %q; %s is the catalog (try `go run ./cmd/spec check`)\n",
		id, displayPath(*rulesPath))
	return 1
}

// renderRuleBrief is the one-rule work order.
func renderRuleBrief(ctx *briefContext, rule Rule, rulesPath string) []byte {
	var b strings.Builder
	b.WriteString(briefHeader)
	fmt.Fprintf(&b, "# Work order — %s: %s\n\n", mdCell(rule.ID), mdCell(rule.Title))
	fmt.Fprintf(&b, "> Generated by `go run ./cmd/spec brief` from the canonical catalog `%s`.\n"+
		"> The catalog entry and its scenario are the source of truth; this is a reading aid.\n\n",
		displayPath(rulesPath))
	writeBriefRule(&b, rule, ctx)
	return finishMarkdown(&b)
}

// renderModuleBrief is the module work order: every rule of the module, in id
// order, under one module heading.
func renderModuleBrief(ctx *briefContext, rules []Rule, module, rulesPath string) []byte {
	var b strings.Builder
	b.WriteString(briefHeader)
	fmt.Fprintf(&b, "# Work order — module `%s`\n\n", mdCell(module))
	fmt.Fprintf(&b, "> Generated by `go run ./cmd/spec brief --module %s` from the canonical catalog `%s`.\n"+
		"> The catalog entries and their scenarios are the source of truth; this is a reading aid.\n\n",
		mdCell(module), displayPath(rulesPath))

	if len(rules) == 0 {
		fmt.Fprintf(&b, "_(no rule in module `%s` yet)_\n\n", mdCell(module))
		return finishMarkdown(&b)
	}

	fmt.Fprintf(&b, "**%d %s** — %s.\n\n", len(rules), plural(len(rules), "rule", "rules"), briefStatusCounts(rules))
	for _, rule := range rules {
		fmt.Fprintf(&b, "## %s — %s\n\n", mdCell(rule.ID), mdCell(rule.Title))
		writeBriefRule(&b, rule, ctx)
	}
	return finishMarkdown(&b)
}

// briefStatusCounts renders "30 implemented, 3 specified-only" over the rules
// given, statuses sorted so the line is stable.
func briefStatusCounts(rules []Rule) string {
	counts := map[string]int{}
	for _, rule := range rules {
		counts[rule.Status]++
	}
	parts := make([]string, 0, len(counts))
	for _, status := range sortedKeys(counts) {
		parts = append(parts, fmt.Sprintf("%d %s", counts[status], status))
	}
	return strings.Join(parts, ", ")
}

// plural picks the singular or plural word for a count.
func plural(n int, singular, pluralWord string) string {
	if n == 1 {
		return singular
	}
	return pluralWord
}

// writeBriefRule renders the body every rule shares, at bold-label depth so a
// single-rule and a module work order use the same block.
func writeBriefRule(b *strings.Builder, rule Rule, ctx *briefContext) {
	fmt.Fprintf(b, "**Statement.** %s\n\n", normalizeProse(rule.Statement))

	fmt.Fprint(b, "| Field | Value |\n| --- | --- |\n")
	fmt.Fprintf(b, "| module | `%s` |\n", mdCell(rule.Module))
	fmt.Fprintf(b, "| entity | `%s` |\n", mdCell(rule.Entity))
	fmt.Fprintf(b, "| category | `%s` |\n", mdCell(rule.Category))
	fmt.Fprintf(b, "| status | `%s` |\n", mdCell(rule.Status))
	fmt.Fprintf(b, "| authority | `%s` |\n", mdCell(rule.Authority))
	if rule.Mechanism != nil {
		fmt.Fprintf(b, "| mechanism | `%s` |\n", mdCell(*rule.Mechanism))
	}
	if rule.Scope != nil {
		fmt.Fprintf(b, "| scope | `%s` |\n", mdCell(*rule.Scope))
	}
	fmt.Fprint(b, "\n")

	// A deviation from the category's default authority is the interesting
	// entry, so the reason from `notes` is promoted out of the Notes block.
	notesShown := false
	if def, ok := categoryDefaultAuthority[rule.Category]; ok && def != rule.Authority {
		fmt.Fprintf(b, "**Authority deviation.** category `%s` defaults to `%s`; this rule's authority is `%s`. Reason, from `notes`:\n\n",
			mdCell(rule.Category), mdCell(def), mdCell(rule.Authority))
		if strings.TrimSpace(rule.Notes) == "" {
			fmt.Fprint(b, "> _(no notes — policy 8 flags this)_\n\n")
		} else {
			writeQuoteBlock(b, rule.Notes)
			notesShown = true
		}
	}

	writeBriefEnforcement(b, rule, ctx)
	writeBriefRefusal(b, rule)

	if rule.Fixture != nil && *rule.Fixture != "" {
		fmt.Fprintf(b, "**Shared fixture.** `%s`\n\n", mdCell(*rule.Fixture))
	} else {
		fmt.Fprint(b, "**Shared fixture.** _(none)_\n\n")
	}

	writeBriefVerification(b, rule, ctx)
	writeBriefScenarios(b, rule, ctx)

	if rule.ExpertRef != nil && *rule.ExpertRef != "" {
		fmt.Fprintf(b, "**Expert ref** `%s`\n\n", mdCell(displayPath(*rule.ExpertRef)))
	}
	if rule.KnowledgeRef != nil && *rule.KnowledgeRef != "" {
		fmt.Fprintf(b, "**Knowledge ref** `%s`\n\n", mdCell(displayPath(*rule.KnowledgeRef)))
	}

	if !notesShown && strings.TrimSpace(rule.Notes) != "" {
		writeNotes(b, rule.Notes)
	}

	writeBriefGate(b)
}

func writeBriefEnforcement(b *strings.Builder, rule Rule, ctx *briefContext) {
	if len(rule.Enforcement) == 0 {
		fmt.Fprint(b, "**Enforcement.** _(no site — a specified-only rule has none yet)_\n\n")
		return
	}
	fmt.Fprint(b, "**Enforcement.**\n\n| Site | Layer | Role | Pinned by | Resolves |\n| --- | --- | --- | --- | --- |\n")
	for _, site := range rule.Enforcement {
		pinned := "—"
		if site.PinnedBy != nil && *site.PinnedBy != "" {
			pinned = "`" + mdCell(*site.PinnedBy) + "`"
		}
		resolved := "yes"
		if !ctx.resolvesEnforcement(site.Site) {
			resolved = "**missing**"
		}
		fmt.Fprintf(b, "| `%s` | `%s` | `%s` | %s | %s |\n",
			mdCell(displayPath(site.Site)), mdCell(site.Layer), mdCell(site.Role), pinned, resolved)
	}
	fmt.Fprint(b, "\n")
}

func writeBriefRefusal(b *strings.Builder, rule Rule) {
	if rule.Refusal == nil {
		fmt.Fprint(b, "**Refusal.** _(none — this rule cannot refuse)_\n\n")
		return
	}

	code := "_(no code)_"
	if rule.Refusal.Code != "" {
		code = "`" + mdCell(rule.Refusal.Code) + "`"
	}
	constraints := "_(unnamed)_"
	if names := rule.Refusal.Constraint; len(names) > 0 {
		quoted := make([]string, 0, len(names))
		for _, name := range names {
			quoted = append(quoted, "`"+mdCell(name)+"`")
		}
		constraints = strings.Join(quoted, ", ")
	}
	sentinel := "_(unmapped)_"
	if rule.Refusal.Sentinel != nil && *rule.Refusal.Sentinel != "" {
		sentinel = "`" + mdCell(*rule.Refusal.Sentinel) + "`"
	}
	http := "_(falls through to 500)_"
	if rule.Refusal.HTTP != nil {
		http = fmt.Sprintf("`%d`", *rule.Refusal.HTTP)
	}

	fmt.Fprint(b, "**Refusal.**\n\n| Code | Constraint | Sentinel | HTTP |\n| --- | --- | --- | --- |\n")
	fmt.Fprintf(b, "| %s | %s | %s | %s |\n\n", code, constraints, sentinel, http)
}

func writeBriefVerification(b *strings.Builder, rule Rule, ctx *briefContext) {
	kinds := []struct {
		kind     string
		pointers []string
	}{
		{"unit", rule.Verification.Unit},
		{"e2e", rule.Verification.E2E},
		{"gherkin", rule.Verification.Gherkin},
	}

	total := 0
	for _, k := range kinds {
		total += len(k.pointers)
	}
	if total == 0 {
		fmt.Fprint(b, "**Verification.** _(no pointer — policy 3 flags an implemented rule without one)_\n\n")
		return
	}

	fmt.Fprint(b, "**Verification.**\n\n| Kind | Pointer | Resolves |\n| --- | --- | --- |\n")
	for _, k := range kinds {
		for _, pointer := range k.pointers {
			resolved := "yes"
			if !ctx.resolvesVerification(k.kind, pointer) {
				resolved = "**missing**"
			}
			fmt.Fprintf(b, "| `%s` | `%s` | %s |\n", mdCell(k.kind), mdCell(displayPath(pointer)), resolved)
		}
	}
	fmt.Fprint(b, "\n")
}

func writeBriefScenarios(b *strings.Builder, rule Rule, ctx *briefContext) {
	refs := ctx.scenariosFor(rule.ID)
	if len(refs) == 0 {
		fmt.Fprintf(b, "**Linked scenarios.** _(none tagged `%s%s` yet)_\n\n", ruleTagPrefix, mdCell(rule.ID))
		return
	}
	fmt.Fprintf(b, "**Linked scenarios** (tagged `%s%s`)\n\n", ruleTagPrefix, mdCell(rule.ID))
	for _, ref := range refs {
		fmt.Fprintf(b, "- `%s`\n", mdCell(ref.pointer()))
	}
	fmt.Fprint(b, "\n")
}

// writeBriefGate names the commands that prove the change. `make audit` is the
// single gate; the targeted three are what a reader runs while iterating.
func writeBriefGate(b *strings.Builder) {
	fmt.Fprint(b, "**Gate**\n\n```sh\nmake spec/gen\nmake spec/check\nmake test/spec\nmake audit\n```\n\n")
	fmt.Fprint(b, "`make test/spec` needs `LT_API_TEST_DSN` (`make db/up` provides it); `make audit` is the whole gate.\n\n")
}

// resolvesEnforcement resolves a site the same way `check` does: a migration
// site when the file exists under the root, a `path::Symbol` site when the
// symbol exists in the file (receiver-aware, via symbolExists), and anything
// malformed as missing.
func (b *briefContext) resolvesEnforcement(site string) bool {
	if site == "" || lineNumberPattern.MatchString(site) {
		return false
	}
	if strings.HasPrefix(site, "migrations/") {
		return b.checker.fileExists(site)
	}
	path, symbol, ok := splitPointer(site)
	if !ok || isLineNumber(symbol) {
		return false
	}
	return b.resolvesSymbol(path, symbol, symbolExists)
}

// resolvesVerification resolves a pointer the same way `check` does: Go
// pointers by `path::Symbol` (test symbols for unit/e2e), scenarios by
// `<feature-file>::<scenario name>` against the parsed tree.
func (b *briefContext) resolvesVerification(kind, pointer string) bool {
	if kind == "gherkin" {
		path, name, ok := splitGherkinPointer(pointer)
		if !ok {
			return false
		}
		_, seen := b.index.byPointer[path+"::"+name]
		return seen
	}
	path, symbol, ok := splitPointer(pointer)
	if !ok || isLineNumber(symbol) {
		return false
	}
	return b.resolvesSymbol(path, symbol, testSymbolExists)
}

func (b *briefContext) resolvesSymbol(path, symbol string, symbolOK func(src, symbol string) bool) bool {
	data, err := os.ReadFile(filepath.Join(b.checker.root, filepath.FromSlash(path)))
	if err != nil {
		return false
	}
	return symbolOK(string(data), symbol)
}

// scenariosFor returns the scenarios tagged with the rule, ordered by file then
// line so a work order does not depend on walk order.
func (b *briefContext) scenariosFor(ruleID string) []scenarioRef {
	refs := make([]scenarioRef, len(b.index.byRule[ruleID]))
	copy(refs, b.index.byRule[ruleID])
	sort.SliceStable(refs, func(i, j int) bool {
		if refs[i].Path != refs[j].Path {
			return refs[i].Path < refs[j].Path
		}
		return refs[i].Line < refs[j].Line
	})
	return refs
}

// writeQuoteBlock renders notes as a block quote, without the Notes heading.
func writeQuoteBlock(b *strings.Builder, text string) {
	for _, line := range strings.Split(strings.TrimSpace(text), "\n") {
		line = strings.TrimSpace(line)
		if line == "" {
			fmt.Fprint(b, ">\n")
			continue
		}
		fmt.Fprintf(b, "> %s\n", escapeQuoteLine(line))
	}
	fmt.Fprint(b, "\n")
}

// orderedListMarker matches a leading `1.`/`12.` list marker; only the dot is
// escaped so the note reads as prose inside the quote, not a nested list.
var orderedListMarker = regexp.MustCompile(`^([0-9]+)\.(?:[ \t]|$)`)

// escapeQuoteLine neutralizes exactly the leading characters that would change
// the Markdown structure of the block quote — a nested quote (`>`), a heading
// (`#`), and a list marker (`-`, `*`, `+`, `1.`). Ordinary prose is untouched.
func escapeQuoteLine(line string) string {
	switch {
	case strings.HasPrefix(line, ">"), strings.HasPrefix(line, "#"):
		return `\` + line
	case strings.HasPrefix(line, "- "), strings.HasPrefix(line, "* "), strings.HasPrefix(line, "+ "),
		line == "-", line == "*", line == "+":
		return `\` + line
	}
	if loc := orderedListMarker.FindStringSubmatchIndex(line); loc != nil {
		dot := loc[3] // end of the digit group, i.e. the `.`
		return line[:dot] + `\` + line[dot:]
	}
	return line
}

// finishMarkdown keeps every generated artifact byte-stable: exactly one
// trailing newline.
func finishMarkdown(b *strings.Builder) []byte {
	return []byte(strings.TrimRight(b.String(), "\n") + "\n")
}
