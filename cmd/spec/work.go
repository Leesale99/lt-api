package main

// work.go is the one work command: `spec work` prints the work queue, `spec
// work <ID>` the per-rule work order (the overlay), and `spec work --module <m>`
// the queue narrowed to one module. One command, one reading aid, so an agent
// never has to know which of two near-identical views to ask for.
//
// The queue answers "what should an agent pick up next?" without running the
// checker. It reads the catalog and the feature tree only — the same pointers
// the overlay resolves — and sorts the work by why it is queued:
//
//	1. drifted        — the catalog and the code disagree; notes say how.
//	2. specified-only — designed, not implemented yet.
//	3. implemented with a statically broken pointer — an enforcement site or a
//	   verification pointer that does not resolve today.
//
// Everything the queue does NOT evaluate (policy 13 step vocabulary, policy 15
// annotations, policy 18 oracle assertions, copy-policy ties, stale-pointer
// notes) is surfaced as a note pointing at `make spec/check`: a queue entry is a
// cheap hint, never a verdict. `check` owns the verdict.
//
// The overlay prints the derived content only. Since B1 the authored prose — the
// statement, the notes body — lives in docs/spec/rules/<module>/<ID>.md, so the
// overlay links to that file instead of restating it. What it adds is what the
// tree says today: whether each enforcement site and verification pointer still
// resolves, the authority deviation, and the gate to run.
//
// It is a reading aid, never a source of truth: the rule file and its scenario
// are the law.

import (
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// The three queue priorities, in emitted order. They are the only reason a
// rule is queued, so a reader never has to guess what "next" means.
const (
	queuePriorityDrifted       = 1
	queuePrioritySpecifiedOnly = 2
	queuePriorityBrokenPointer = 3
)

// workHeader marks the output as generated in the same voice as the other
// catalog views: a work order is derived, so editing it would be editing the
// wrong file.
const workHeader = `<!-- GENERATED by spec work — a reading aid, not a source of truth. -->

`

// queueReasonLimit is how much of a catalog note the queue prints. A queue row
// is a pointer into the rule, not the rule itself: `spec work <ID>` is where
// the rule is read.
const queueReasonLimit = 160

// workContext resolves the pointers a work order prints: catalog paths against
// the checkout, scenarios against the parsed feature tree.
type workContext struct {
	checker *checker
	index   *featureIndex
}

func newWorkContext(root string) *workContext {
	c := &checker{root: root, fixtures: map[string]bool{}}
	return &workContext{checker: c, index: c.indexFeatures()}
}

// workTask is one packet of work, displayed as a queue row. The priority is one
// of queuePriority* and orders the queue; the row also carries `status`, so a
// reader never has to translate a number.
type workTask struct {
	RuleID  string
	Title   string
	Module  string
	Status  string
	Reason  string
	WorkCmd string
	GateCmd string

	priority int
}

func runWork(args []string, stdout, stderr io.Writer) int {
	fs := flag.NewFlagSet("spec work", flag.ContinueOnError)
	fs.SetOutput(stderr)
	rulesPath := fs.String("rules", "docs/spec/rules", "path to the per-rule-file catalog directory")
	module := fs.String("module", "", "narrow the work queue to one module")
	if err := fs.Parse(args); err != nil {
		return 2
	}

	switch {
	case *module != "" && fs.NArg() > 0:
		fmt.Fprintf(stderr, "spec work: --module takes no rule id (got %q)\n", fs.Arg(0))
		return 2
	case fs.NArg() > 1:
		fmt.Fprintf(stderr, "spec work: expected at most one rule id, got %d\n\n"+
			"usage: spec work                 (the work queue)\n"+
			"       spec work R-XXX-NNN       (one rule's work order)\n"+
			"       spec work --module %s  (the queue for one module)\n", fs.NArg(), catalogModules()[0])
		return 2
	}

	if fs.NArg() == 1 {
		return runWorkRule(*rulesPath, strings.TrimSpace(fs.Arg(0)), stdout, stderr)
	}
	return runWorkQueue(*rulesPath, *module, stdout, stderr)
}

// runWorkRule prints the per-rule work order (the overlay).
func runWorkRule(rulesPath, id string, stdout, stderr io.Writer) int {
	catalog, err := loadCatalog(rulesPath)
	if err != nil {
		fmt.Fprintf(stderr, "spec work: %v\n", err)
		return 1
	}
	root, err := repoRoot(rulesPath)
	if err != nil {
		fmt.Fprintf(stderr, "spec work: %v\n", err)
		return 1
	}
	for _, rule := range sortedRules(catalog) {
		if rule.ID == id {
			_, _ = stdout.Write(renderWorkRule(newWorkContext(root), rule, rulesPath))
			return 0
		}
	}
	fmt.Fprintf(stderr, "spec work: unknown rule id %q; %s is the catalog (try `go run ./cmd/spec check`)\n",
		id, displayPath(rulesPath))
	return 1
}

// runWorkQueue prints the work queue, optionally narrowed to one module.
func runWorkQueue(rulesPath, module string, stdout, stderr io.Writer) int {
	// An unknown module is a usage error (2), matching `spec check`: the flag
	// can only be wrong, and a caller feeding it from a script wants the bad
	// invocation distinguished from a broken checkout.
	scope, err := ParseCLI(module, "")
	if err != nil {
		fmt.Fprintf(stderr, "spec work: %v\n", err)
		return 2
	}

	catalog, err := loadCatalog(rulesPath)
	if err != nil {
		fmt.Fprintf(stderr, "spec work: %v\n", err)
		return 1
	}
	root, err := repoRoot(rulesPath)
	if err != nil {
		fmt.Fprintf(stderr, "spec work: %v\n", err)
		return 1
	}

	rules := sortedRules(catalog)
	selected := rules
	if module != "" {
		if err := scope.Resolve(catalog, displayPath(rulesPath)); err != nil {
			fmt.Fprintf(stderr, "spec work: %v\n", err)
			return 1
		}
		selected = scope.Select(rules)
	}

	_, _ = stdout.Write(renderWorkQueue(buildQueue(newWorkContext(root), selected), selected, module, rulesPath))
	return 0
}

// ruleFilePath is the authored rule file for a rule: the statement and the
// notes body live there, so the overlay links to it instead of copying it.
func ruleFilePath(rulesPath string, rule Rule) string {
	return filepath.Join(rulesPath, rule.Module, rule.ID+".md")
}

// renderWorkRule is the one-rule work order: the overlay only.
func renderWorkRule(ctx *workContext, rule Rule, rulesPath string) []byte {
	var b strings.Builder
	b.WriteString(workHeader)
	fmt.Fprintf(&b, "# Work order — %s: %s\n\n", mdCell(rule.ID), mdCell(rule.Title))
	fmt.Fprintf(&b, "> Generated by `go run ./cmd/spec work %s` from the canonical catalog `%s`.\n"+
		"> Source of truth: the rule file `%s` and its scenarios.\n"+
		"> The statement and the notes body live there; this overlay prints only what is\n"+
		"> derived — resolved pointers, the authority deviation, and the gate.\n\n",
		mdCell(rule.ID), displayPath(rulesPath), displayPath(ruleFilePath(rulesPath, rule)))
	writeWorkRule(&b, rule, ctx)
	return finishMarkdown(&b)
}

// writeWorkRule renders the overlay every work order shares.
func writeWorkRule(b *strings.Builder, rule Rule, ctx *workContext) {
	fmt.Fprint(b, "| Field | Value |\n| --- | --- |\n")
	fmt.Fprintf(b, "| module | `%s` |\n", mdCell(rule.Module))
	fmt.Fprintf(b, "| entity | `%s` |\n", mdCell(rule.Entity))
	fmt.Fprintf(b, "| category | `%s` |\n", mdCell(rule.Category))
	fmt.Fprintf(b, "| status | `%s` |\n", mdCell(rule.Status))
	fmt.Fprintf(b, "| authority | `%s` |\n", mdCell(rule.Authority))
	if rule.Mechanism != nil {
		fmt.Fprintf(b, "| mechanism | `%s` |\n", mdCell(*rule.Mechanism))
	}
	if rule.WriteScope != nil {
		fmt.Fprintf(b, "| write_scope | `%s` |\n", mdCell(*rule.WriteScope))
	}
	fmt.Fprint(b, "\n")

	// A deviation from the category's default authority is the interesting
	// entry, so it is promoted out of the rule file's Notes body — as a pointer
	// to that body, never a copy of it.
	if def, ok := categoryDefaultAuthority[rule.Category]; ok && def != rule.Authority {
		fmt.Fprintf(b, "**Authority deviation.** category `%s` defaults to `%s`; this rule's authority is `%s`. The reason is in the rule file's `## Notes` body.\n\n",
			mdCell(rule.Category), mdCell(def), mdCell(rule.Authority))
	}

	writeWorkEnforcement(b, rule, ctx)
	writeWorkRefusal(b, rule)

	if rule.Fixture != nil && *rule.Fixture != "" {
		fmt.Fprintf(b, "**Shared fixture.** `%s`\n\n", mdCell(*rule.Fixture))
	} else {
		fmt.Fprint(b, "**Shared fixture.** _(none)_\n\n")
	}

	writeWorkVerification(b, rule, ctx)
	writeWorkScenarios(b, rule, ctx)

	if rule.ExpertRef != nil && *rule.ExpertRef != "" {
		fmt.Fprintf(b, "**Expert ref** `%s`\n\n", mdCell(displayPath(*rule.ExpertRef)))
	}
	if rule.KnowledgeRef != nil && *rule.KnowledgeRef != "" {
		fmt.Fprintf(b, "**Knowledge ref** `%s`\n\n", mdCell(displayPath(*rule.KnowledgeRef)))
	}

	writeStructuredNotes(b, rule)
	writeWorkGate(b)
}

func writeWorkEnforcement(b *strings.Builder, rule Rule, ctx *workContext) {
	if len(rule.Enforcement) == 0 {
		fmt.Fprint(b, "**Enforcement.** _(no site — a specified-only rule has none yet)_\n\n")
		return
	}
	fmt.Fprint(b, "**Enforcement.**\n\n| Site | Layer | Role | Pinned by | Resolves |\n| --- | --- | --- | --- | --- |\n")
	for _, site := range rule.Enforcement {
		pinned := "—"
		if site.PinnedBy != nil && *site.PinnedBy != "" {
			pinned = "`" + mdCell(*site.PinnedBy) + "`"
		}
		resolved := "yes"
		if !ctx.resolvesEnforcement(site.Site) {
			resolved = "**missing**"
		}
		fmt.Fprintf(b, "| `%s` | `%s` | `%s` | %s | %s |\n",
			mdCell(displayPath(site.Site)), mdCell(site.Layer), mdCell(site.Role), pinned, resolved)
	}
	fmt.Fprint(b, "\n")
}

func writeWorkRefusal(b *strings.Builder, rule Rule) {
	if rule.Refusal == nil {
		fmt.Fprint(b, "**Refusal.** _(none — this rule cannot refuse)_\n\n")
		return
	}

	code := "_(no code)_"
	if rule.Refusal.Code != "" {
		code = "`" + mdCell(rule.Refusal.Code) + "`"
	}
	constraints := "_(unnamed)_"
	if names := rule.Refusal.Constraint; len(names) > 0 {
		quoted := make([]string, 0, len(names))
		for _, name := range names {
			quoted = append(quoted, "`"+mdCell(name)+"`")
		}
		constraints = strings.Join(quoted, ", ")
	}
	sentinel := "_(unmapped)_"
	if rule.Refusal.Sentinel != nil && *rule.Refusal.Sentinel != "" {
		sentinel = "`" + mdCell(*rule.Refusal.Sentinel) + "`"
	}
	http := "_(falls through to 500)_"
	if rule.Refusal.HTTP != nil {
		http = fmt.Sprintf("`%d`", *rule.Refusal.HTTP)
	}

	fmt.Fprint(b, "**Refusal.**\n\n| Code | Constraint | Sentinel | HTTP |\n| --- | --- | --- | --- |\n")
	fmt.Fprintf(b, "| %s | %s | %s | %s |\n\n", code, constraints, sentinel, http)
}

func writeWorkVerification(b *strings.Builder, rule Rule, ctx *workContext) {
	kinds := []struct {
		kind     string
		pointers []string
	}{
		{"unit", rule.Verification.Unit},
		{"e2e", rule.Verification.E2E},
		{"gherkin", rule.Verification.Gherkin},
	}

	total := 0
	for _, k := range kinds {
		total += len(k.pointers)
	}
	if total == 0 {
		fmt.Fprint(b, "**Verification.** _(no pointer — policy 3 flags an implemented rule without one)_\n\n")
		return
	}

	fmt.Fprint(b, "**Verification.**\n\n| Kind | Pointer | Resolves |\n| --- | --- | --- |\n")
	for _, k := range kinds {
		for _, pointer := range k.pointers {
			resolved := "yes"
			if !ctx.resolvesVerification(k.kind, pointer) {
				resolved = "**missing**"
			}
			fmt.Fprintf(b, "| `%s` | `%s` | %s |\n", mdCell(k.kind), mdCell(displayPath(pointer)), resolved)
		}
	}
	fmt.Fprint(b, "\n")
}

func writeWorkScenarios(b *strings.Builder, rule Rule, ctx *workContext) {
	refs := ctx.scenariosFor(rule.ID)
	if len(refs) == 0 {
		fmt.Fprintf(b, "**Linked scenarios.** _(none tagged `%s%s` yet)_\n\n", ruleTagPrefix, mdCell(rule.ID))
		return
	}
	fmt.Fprintf(b, "**Linked scenarios** (tagged `%s%s`)\n\n", ruleTagPrefix, mdCell(rule.ID))
	for _, ref := range refs {
		fmt.Fprintf(b, "- `%s`\n", mdCell(ref.pointer()))
	}
	fmt.Fprint(b, "\n")
}

// writeWorkGate names the commands that prove the change. `make audit` is the
// single gate; the targeted three are what a reader runs while iterating.
func writeWorkGate(b *strings.Builder) {
	fmt.Fprint(b, "**Gate**\n\n```sh\nmake spec/gen\nmake spec/check\nmake test/spec\nmake audit\n```\n\n")
	fmt.Fprint(b, "`make test/spec` needs `LT_API_TEST_DSN` (`make db/up` provides it); `make audit` is the whole gate.\n\n")
}

// buildQueue turns catalog rules into ordered task packets. Input is in id
// order and the sort is stable on (priority, id), so the output never depends on
// map iteration or on the order the catalog happened to list the rules.
func buildQueue(ctx *workContext, rules []Rule) []workTask {
	tasks := make([]workTask, 0, len(rules))
	for _, rule := range rules {
		reason, priority, queued := queueReason(ctx, rule)
		if !queued {
			continue
		}
		tasks = append(tasks, workTask{
			RuleID:   rule.ID,
			Title:    normalizeProse(rule.Title),
			Module:   rule.Module,
			Status:   rule.Status,
			Reason:   reason,
			WorkCmd:  "make spec/work args='" + rule.ID + "'",
			GateCmd:  "go run ./cmd/spec check --strict --rule " + rule.ID,
			priority: priority,
		})
	}
	sortQueue(tasks)
	return tasks
}

// queueReason decides whether a rule is queued and why. It deliberately uses
// only the cheap resolvers the work overlay uses: anything needing the full
// checker is out of scope and reported as such by the caller.
func queueReason(ctx *workContext, rule Rule) (reason string, priority int, queued bool) {
	switch rule.Status {
	case statusDrifted:
		reason = "catalog status is drifted"
		if note := queueFirstLine(rule.Notes); note != "" {
			reason += "; notes: " + note
		} else {
			reason += " and notes are empty (policy 5 flags this)"
		}
		return reason, queuePriorityDrifted, true

	case statusSpecifiedOnly:
		reason = "designed but not implemented"
		if rule.ExpertRef != nil && strings.TrimSpace(*rule.ExpertRef) != "" {
			reason += "; expert-ref " + displayPath(*rule.ExpertRef)
		} else {
			reason += "; catalog carries no expert-ref (policy 4 flags this)"
		}
		return reason, queuePrioritySpecifiedOnly, true
	}

	broken := unresolvedPointers(ctx, rule)
	if len(broken) == 0 {
		return "", 0, false
	}
	return "unresolved pointer: " + strings.Join(broken, "; "), queuePriorityBrokenPointer, true
}

// unresolvedPointers lists the enforcement sites and verification pointers a
// rule declares that do not resolve in this checkout, in catalog order (so the
// reason is deterministic). It is intentionally shallow: file existence and a
// symbol scan, no annotation or vocabulary policy.
func unresolvedPointers(ctx *workContext, rule Rule) []string {
	broken := make([]string, 0, len(rule.Enforcement)+
		len(rule.Verification.Unit)+len(rule.Verification.E2E)+len(rule.Verification.Gherkin))

	for _, site := range rule.Enforcement {
		if !ctx.resolvesEnforcement(site.Site) {
			broken = append(broken, "enforcement site "+displayPath(site.Site))
		}
	}
	kinds := []struct {
		kind     string
		pointers []string
	}{
		{"unit", rule.Verification.Unit},
		{"e2e", rule.Verification.E2E},
		{"gherkin", rule.Verification.Gherkin},
	}
	for _, k := range kinds {
		for _, pointer := range k.pointers {
			if !ctx.resolvesVerification(k.kind, pointer) {
				broken = append(broken, k.kind+" pointer "+displayPath(pointer))
			}
		}
	}
	return broken
}

// sortQueue orders by priority, then by rule id. Both keys are total, so the
// queue is byte-stable across runs whatever order the catalog listed.
func sortQueue(tasks []workTask) {
	sort.SliceStable(tasks, func(i, j int) bool { return queueLess(tasks[i], tasks[j]) })
}

func queueLess(a, b workTask) bool {
	if a.priority != b.priority {
		return a.priority < b.priority
	}
	return a.RuleID < b.RuleID
}

// renderWorkQueue is the human-readable queue: header with the status counts,
// the priority legend, the table, and the boundary of what the queue evaluates.
func renderWorkQueue(tasks []workTask, rules []Rule, module, rulesPath string) []byte {
	var b strings.Builder
	b.WriteString(workHeader)
	b.WriteString("# Spec work queue\n\n")
	scope := "the whole catalog"
	if module != "" {
		scope = "module `" + mdCell(module) + "`"
	}
	fmt.Fprintf(&b, "> Generated by `go run ./cmd/spec work` from the canonical catalog `%s` (%s).\n"+
		"> The rule files and their scenarios are the source of truth; this is a reading aid.\n\n",
		displayPath(rulesPath), scope)

	switch {
	case len(rules) == 0:
		fmt.Fprint(&b, "**No rule in scope** — the catalog (or the selected module) is empty.\n\n")
	default:
		fmt.Fprintf(&b, "**%d %s** — %s.\n\n",
			len(rules), plural(len(rules), "rule", "rules"), ruleStatusCounts(rules))
	}
	fmt.Fprint(&b, "**Priority order.** 1 drifted (the catalog and the code disagree) → "+
		"2 specified-only (designed, not implemented) → "+
		"3 implemented but with an enforcement site or verification pointer that does not resolve today.\n\n")

	if len(tasks) == 0 {
		fmt.Fprint(&b, "**The queue is empty** — no drifted rule, no specified-only rule, "+
			"and no implemented rule with an unresolved enforcement site or verification pointer.\n\n")
		writeQueueScopeNote(&b)
		return finishMarkdown(&b)
	}

	fmt.Fprint(&b, "| Priority | Rule | Title | Module | Status | Reason |\n"+
		"| --- | --- | --- | --- | --- | --- |\n")
	for _, task := range tasks {
		fmt.Fprintf(&b, "| %d | `%s` | %s | `%s` | `%s` | %s |\n",
			task.priority, mdCell(task.RuleID), mdCell(task.Title), mdCell(task.Module),
			mdCell(task.Status), mdCell(task.Reason))
	}
	fmt.Fprintf(&b, "\n**Next step.** Take the top row; `%s` (or `go run ./cmd/spec work %s`) prints its work order, "+
		"and `%s` is its scoped gate.\n\n", tasks[0].WorkCmd, tasks[0].RuleID, tasks[0].GateCmd)

	writeQueueScopeNote(&b)
	return finishMarkdown(&b)
}

// writeQueueScopeNote draws the boundary between the cheap queue and the full
// checker. It is a note, not a finding: the queue never claims a policy passed.
func writeQueueScopeNote(b *strings.Builder) {
	fmt.Fprint(b, "> **Not evaluated here.** Step vocabulary (policy 13), `//rule:` annotations "+
		"(policy 15), oracle assertions (policy 18), copy-policy ties, and stale-pointer notes all "+
		"need the full checker: run `make spec/check` (or `make audit`) for the authoritative verdict.\n")
}

// queueFirstLine folds a catalog note to one short line so the table row keeps
// a single line and the queue stays scannable.
func queueFirstLine(note string) string {
	flat := normalizeProse(note)
	runes := []rune(flat)
	if len(runes) <= queueReasonLimit {
		return flat
	}
	return strings.TrimRight(string(runes[:queueReasonLimit]), " ") + "…"
}

// ruleStatusCounts renders "30 implemented, 3 specified-only" over the rules
// given, statuses sorted so the line is stable. Both `spec work` and the
// generated dashboard headline use it.
func ruleStatusCounts(rules []Rule) string {
	counts := map[string]int{}
	for _, rule := range rules {
		counts[rule.Status]++
	}
	parts := make([]string, 0, len(counts))
	for _, status := range sortedKeys(counts) {
		parts = append(parts, fmt.Sprintf("%d %s", counts[status], status))
	}
	return strings.Join(parts, ", ")
}

// plural picks the singular or plural word for a count.
func plural(n int, singular, pluralWord string) string {
	if n == 1 {
		return singular
	}
	return pluralWord
}

// resolvesEnforcement resolves a site the same way `check` does: a migration
// site when the file exists under the root, a `path::Symbol` site when the
// symbol exists in the file (receiver-aware, via symbolExists), and anything
// malformed as missing.
func (b *workContext) resolvesEnforcement(site string) bool {
	if site == "" || lineNumberPattern.MatchString(site) {
		return false
	}
	if strings.HasPrefix(site, "migrations/") {
		return b.checker.fileExists(site)
	}
	path, symbol, ok := splitPointer(site)
	if !ok || isLineNumber(symbol) {
		return false
	}
	return b.resolvesSymbol(path, symbol, symbolExists)
}

// resolvesVerification resolves a pointer the same way `check` does: Go
// pointers by `path::Symbol` (test symbols for unit/e2e), scenarios by
// `<feature-file>::<scenario name>` against the parsed tree.
func (b *workContext) resolvesVerification(kind, pointer string) bool {
	if kind == "gherkin" {
		path, name, ok := splitGherkinPointer(pointer)
		if !ok {
			return false
		}
		_, seen := b.index.byPointer[path+"::"+name]
		return seen
	}
	path, symbol, ok := splitPointer(pointer)
	if !ok || isLineNumber(symbol) {
		return false
	}
	return b.resolvesSymbol(path, symbol, testSymbolExists)
}

func (b *workContext) resolvesSymbol(path, symbol string, symbolOK func(src, symbol string) bool) bool {
	data, err := os.ReadFile(filepath.Join(b.checker.root, filepath.FromSlash(path)))
	if err != nil {
		return false
	}
	return symbolOK(string(data), symbol)
}

// scenariosFor returns the scenarios tagged with the rule, ordered by file then
// line so a work order does not depend on walk order.
func (b *workContext) scenariosFor(ruleID string) []scenarioRef {
	refs := make([]scenarioRef, len(b.index.byRule[ruleID]))
	copy(refs, b.index.byRule[ruleID])
	sort.SliceStable(refs, func(i, j int) bool {
		if refs[i].Path != refs[j].Path {
			return refs[i].Path < refs[j].Path
		}
		return refs[i].Line < refs[j].Line
	})
	return refs
}
