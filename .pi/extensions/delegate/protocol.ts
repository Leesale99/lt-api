/**
 * Task-packet protocol: the ONE owner of the task-packet grammar.
 *
 * A task text handed to the `subagent` tool is a task packet. Two machine
 * readable lines are reserved; everything else is prose for the worker.
 *
 *   SPEC-SCOPE: none
 *   SPEC-SCOPE: module=<m>
 *   SPEC-SCOPE: rules=<id,...>
 *   SPEC-SCOPE: module=<m> rules=<id,...>
 *   CLAIMS-PATHS: <glob>,<glob>,...
 *
 * Semantics:
 *   - At most ONE `SPEC-SCOPE:` line per packet. A packet with NO such line is
 *     still valid: it means "full spec check", and the spawn boundary
 *     (./dispatch.ts → ./spawn.ts) exports NO `PI_DELEGATE_SPEC_SCOPE` env var
 *     for it (today's behavior).
 *   - `none` is an EXPLICIT empty scope, distinct from "no line at all". Its
 *     normalized env value is the literal string `none`: formatSpecScope() of
 *     an empty scope returns `none`, and parseSpecScopeEnv("none") recognizes
 *     it as an empty scope (`{ module: undefined, rules: [] }`). The gate
 *     ladders treat an empty scope as "no scoped argv" and therefore run the
 *     declared FULL spec check — the same command the no-line packet gets, but
 *     the intent is recorded (and, from B3.2, the approval relay can read it).
 *   - `module` and `rules` are optional individually but exactly one of them
 *     (or `none`) must be present, in a fixed token grammar: each
 *     whitespace-separated token is `module=<m>` or `rules=<id,...>`, at most
 *     one of each. `modul=game`, `none extra-words`, `rules=`, a bare
 *     `SPEC-SCOPE:` and a second SPEC-SCOPE line are all INVALID.
 *   - `CLAIMS-PATHS:` entries are comma-separated, repo-relative; `./
 *     prefixes and trailing slashes are normalized away. An empty
 *     (whitespace-only) entry is an ERROR, not a silent drop. The first
 *     CLAIMS-PATHS line wins (today's semantics).
 *
 * Failure behavior: `parseTaskPacket` is the authoritative, strict parse. The
 * `subagent` tool boundary calls it once per task text and REFUSES the whole
 * spawn on any error, before a claim is written, a sandbox is created or a
 * child is spawned; the tool result is the refusal naming the offending line
 * (formatTaskPacketRefusal). The lenient helpers below (parseSpecScope,
 * parseClaimsPaths) exist for backward compatibility with the claims log and
 * the approval relay (B3.2 migrates the latter); they must never gate a spawn.
 *
 * Doc-of-record: the `## Task packets` section of the repo-root WORKFLOW.md.
 * That section is generated by hand but owned by THIS module — change the
 * grammar here and in that section together.
 *
 * Loader gotcha (pi 1.5.2 extension parser): avoid `?:` ternaries containing
 * double-quoted strings inside a template literal's ${} — this module sticks to
 * string concatenation, so nothing here can trip that parser.
 */

/** Line prefix that carries a spawn's spec scope in the task text. */
export const SPEC_SCOPE_PREFIX = "SPEC-SCOPE:";
/** Line prefix that carries a spawn's owned paths in the task text. */
export const CLAIMS_PATHS_PREFIX = "CLAIMS-PATHS:";
/** Normalized PI_DELEGATE_SPEC_SCOPE value for an explicit empty scope. */
export const NONE_SCOPE_ENV = "none";

/** The spec scope a task packet names (module and/or rule ids). */
export interface SpecScope {
  module?: string;
  rules: string[];
}

/**
 * One parsed task packet. `scope === null` means "no SPEC-SCOPE line at all"
 * (full check, no env var); an explicit `none` line yields an EMPTY scope and
 * `scopeEnv === "none"`.
 */
export interface TaskPacket {
  scope: SpecScope | null;
  /** Normalized CLAIMS-PATHS globs; empty when the packet has no such line. */
  ownedPaths: string[];
  /** Normalized PI_DELEGATE_SPEC_SCOPE value; absent when no SPEC-SCOPE line. */
  scopeEnv?: string;
}

/** Strict packet parse: ok (with the packet) or the errors naming each line. */
export type TaskPacketParse = { ok: true; packet: TaskPacket } | { ok: false; errors: string[] };

const MODULE_VALUE = /^[A-Za-z0-9_./-]+$/;
const RULE_ID = /^[A-Za-z0-9_-]+$/;
const SCOPE_GRAMMAR =
  "expected none | module=<m> | rules=<id,...> | module=<m> rules=<id,...>";

/**
 * Parse a SPEC-SCOPE body ("module=game rules=R-A-1,R-B-2") into a scope.
 * Lenient: returns null when neither module nor rules is present, so a bare or
 * garbage line is IGNORED (backward-compatible helper for the claims log /
 * approval relay — the spawn boundary uses the strict parse below). `none`
 * parses to an explicit empty scope.
 */
export function parseScopeBody(body: string): SpecScope | null {
  const text = body.trim();
  if (!text) return null;
  if (text.toLowerCase() === NONE_SCOPE_ENV) return { module: undefined, rules: [] };
  const moduleMatch = /module=([A-Za-z0-9_./-]+)/.exec(text);
  const rulesMatch = /rules=([A-Za-z0-9_.,/-]+)/.exec(text);
  const module = moduleMatch ? normalizeModule(moduleMatch[1]) : undefined;
  const rules = rulesMatch
    ? rulesMatch[1]
        .split(",")
        .map((rule) => rule.trim())
        .filter((rule) => RULE_ID.test(rule))
    : [];
  if (!module && rules.length === 0) return null;
  return { module, rules };
}

/**
 * Lenient SPEC-SCOPE extraction (first usable line wins). Kept for the claims
 * log and the approval relay; a spawn is gated by `parseTaskPacket` instead.
 */
export function parseSpecScope(text: string): SpecScope | null {
  for (const rawLine of text.split("\n")) {
    const line = rawLine.trim();
    if (!line.toUpperCase().startsWith(SPEC_SCOPE_PREFIX)) continue;
    const scope = parseScopeBody(line.slice(SPEC_SCOPE_PREFIX.length));
    if (scope) return scope;
  }
  return null;
}

/**
 * Parse the PI_DELEGATE_SPEC_SCOPE env value (already normalized by the
 * task-packet boundary in ./dispatch.ts).
 * Lenient: a hand-set value in either "module=… rules=…" or bare "rules=…"
 * form is accepted; `none` is an explicit empty scope; unusable values yield
 * null (→ full check).
 */
export function parseSpecScopeEnv(value: string | undefined): SpecScope | null {
  if (!value || !value.trim()) return null;
  return parseScopeBody(value);
}

/** Normalized single-line form exported into PI_DELEGATE_SPEC_SCOPE. */
export function formatSpecScope(scope: SpecScope): string {
  const parts: string[] = [];
  if (scope.module) parts.push("module=" + scope.module);
  if (scope.rules.length > 0) parts.push("rules=" + scope.rules.join(","));
  if (parts.length === 0) return NONE_SCOPE_ENV;
  return parts.join(" ");
}

/**
 * Lenient CLAIMS-PATHS extraction (first line with usable entries wins).
 * Kept for the claims log; a spawn is gated by `parseTaskPacket` instead.
 */
export function parseClaimsPaths(text: string): string[] {
  for (const rawLine of text.split("\n")) {
    const line = rawLine.trim();
    if (!line.toUpperCase().startsWith(CLAIMS_PATHS_PREFIX)) continue;
    const body = line.slice(CLAIMS_PATHS_PREFIX.length);
    const paths = body
      .split(",")
      .map((entry) => normalizePathEntry(entry))
      .filter((entry) => entry.length > 0 && !/\s/.test(entry));
    if (paths.length > 0) return paths;
  }
  return [];
}

function normalizeModule(value: string): string {
  return value.replace(/[./]+$/, "");
}

function normalizePathEntry(entry: string): string {
  return entry.trim().replace(/^\.\//, "").replace(/\/+$/, "");
}

/** Strict SPEC-SCOPE body parse. Every token must be part of the grammar. */
function parseScopeBodyStrict(
  body: string,
): { ok: true; scope: SpecScope } | { ok: false; reason: string } {
  const text = body.trim();
  if (!text) return { ok: false, reason: "empty body; " + SCOPE_GRAMMAR };
  if (text.toLowerCase() === NONE_SCOPE_ENV) return { ok: true, scope: { module: undefined, rules: [] } };
  let module: string | undefined;
  const rules: string[] = [];
  const seen = new Set<string>();
  for (const token of text.split(/\s+/)) {
    const eq = token.indexOf("=");
    if (eq <= 0) return { ok: false, reason: 'unrecognized token "' + token + '"; ' + SCOPE_GRAMMAR };
    const key = token.slice(0, eq);
    const value = token.slice(eq + 1);
    if (key !== "module" && key !== "rules") {
      return { ok: false, reason: 'unknown key "' + key + '"; ' + SCOPE_GRAMMAR };
    }
    if (seen.has(key)) return { ok: false, reason: 'duplicate "' + key + '=" in one line' };
    seen.add(key);
    if (key === "module") {
      if (!value || !MODULE_VALUE.test(value) || !normalizeModule(value)) {
        return { ok: false, reason: 'invalid module value "' + value + '"' };
      }
      module = normalizeModule(value);
      continue;
    }
    if (!value) return { ok: false, reason: "empty rules list (expected <id,...>)" };
    for (const entry of value.split(",")) {
      if (!entry) return { ok: false, reason: 'empty rule id in "' + value + '"' };
      if (!RULE_ID.test(entry)) return { ok: false, reason: 'invalid rule id "' + entry + '"' };
      rules.push(entry);
    }
  }
  return { ok: true, scope: { module, rules } };
}

/**
 * Authoritative parse of ONE task packet. Strict: every SPEC-SCOPE line must
 * match the grammar (at most one line), and every CLAIMS-PATHS entry must be a
 * non-empty path. Errors name the offending raw line, and are what the
 * `subagent` boundary returns (via formatTaskPacketRefusal) instead of spawning.
 */
export function parseTaskPacket(text: string): TaskPacketParse {
  const errors: string[] = [];
  let scope: SpecScope | null = null;
  let scopeSeen = false;
  let claimsSeen = false;
  let ownedPaths: string[] = [];
  for (const rawLine of String(text).split("\n")) {
    const line = rawLine.trim();
    const upper = line.toUpperCase();
    if (upper.startsWith(SPEC_SCOPE_PREFIX)) {
      if (scopeSeen) {
        errors.push('SPEC-SCOPE line "' + line + '": at most one SPEC-SCOPE line per task packet');
        continue;
      }
      scopeSeen = true;
      const parsed = parseScopeBodyStrict(line.slice(SPEC_SCOPE_PREFIX.length));
      if (!parsed.ok) errors.push('SPEC-SCOPE line "' + line + '": ' + parsed.reason);
      else scope = parsed.scope;
      continue;
    }
    if (upper.startsWith(CLAIMS_PATHS_PREFIX)) {
      // First CLAIMS-PATHS line wins (today's semantics); a whitespace-only
      // entry in it is an error, never a silent drop.
      if (claimsSeen) continue;
      claimsSeen = true;
      const entries = line.slice(CLAIMS_PATHS_PREFIX.length).split(",");
      const paths: string[] = [];
      for (let index = 0; index < entries.length; index += 1) {
        const normalized = normalizePathEntry(entries[index]);
        if (normalized.length === 0) {
          errors.push(
            'CLAIMS-PATHS line "' +
              line +
              '": entry ' +
              String(index + 1) +
              " is empty (whitespace-only); expected a repo-relative glob between commas",
          );
          continue;
        }
        if (/\s/.test(normalized)) {
          errors.push(
            'CLAIMS-PATHS line "' + line + '": entry "' + normalized + '" contains whitespace',
          );
          continue;
        }
        paths.push(normalized);
      }
      if (paths.length > 0) ownedPaths = paths;
    }
  }
  if (errors.length > 0) return { ok: false, errors };
  const packet: TaskPacket = { scope, ownedPaths };
  if (scope) packet.scopeEnv = formatSpecScope(scope);
  return { ok: true, packet };
}

/**
 * The subagent tool-result text for a refused packet: states the refusal, lists
 * every error (each names its offending line) and points at the doc-of-record.
 */
export function formatTaskPacketRefusal(errors: string[]): string {
  const lines = [
    "Refused: malformed task packet — no claim was written and no worker was spawned.",
  ];
  for (const error of errors) lines.push("- " + error);
  lines.push("");
  lines.push("Task-packet grammar: WORKFLOW.md § Task packets (owner: .pi/extensions/delegate/protocol.ts).");
  return lines.join("\n");
}
